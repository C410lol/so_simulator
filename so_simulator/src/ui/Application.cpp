/*
    Prints the introduction of the program,
    asks if the user wants to use a config file and gets the file path.
    Code generated by Google Gemini on 10/17/2026.
*/
void Application::printIntroduction(std::string& answer, std::string& filePath)
{
    clearScreen();
    std::cout << "=== BEM-VINDO AO SIMULADOR DE SO ===\n\n";
    std::cout << "Deseja carregar um arquivo de configuração? (s/n): ";
    std::cin >> answer;

    if (answer == "s" || answer == "S") {
        std::cout << "\nDigite o caminho completo do arquivo.\n";
        std::cout << "(Ex Windows: E:\\pasta\\config.json | Ex Linux: /media/pendrive/config.json)\n";
        std::cout << "Caminho: ";

        // Limpa o buffer do cin antes de ler a string com espaços
        std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');
        std::getline(std::cin, filePath);

        std::cout << "\nCarregando configurações de: " << filePath << "...\n";

        // Pausa rápida para o usuário ler a mensagem antes de limpar a tela (opcional)
        std::cout << "Pressione Enter para iniciar a simulação...";
        std::cin.get();
    } else {
        //  If the user did not select a config file, we use a default one
        filePath.append("../config-files/teste1.txt");

        std::cout << "\nPulando configuração. Iniciando com valores padrão...\n";
        std::cout << "Pressione Enter para iniciar a simulação...";
        std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');
        std::cin.get();
    }
    clearScreen();
}

/*
    Prints all the infos of the simulation
*/
void Application::render()
{
    printGraphic();
    printReadyQueue();
    printCpus();
    printTasks();
}

void Application::printGraphic()
{
    std::cout << "==================== GRÁFICO GANTT ====================

";

    const std::vector<Task*> tasks = simulation.getTasks();
    for (int i = tasks.size() - 1; i >= 0; i--)
    {
        Task* task = tasks.at(i);
        const std::vector<TaskInstance*> instances = task->getInstances();
        for (int j = instances.size() - 1; j >= 0; j--)
        {
            TaskInstance* instance = instances.at(i);
            std::cout << "T" << task->getId() << "." << instance->getInstanceNumber() << " | ";

        }
    }

    std::cout << "=======================================================

";
}

void Application::printReadyQueue()
{
    std::cout << "==================== FILA DE PRONTOS ====================" << '\n';

    for (TaskInstance* instance: simulation.getReadyQueue())
    {
        std::cout << '\n';

        std::cout << "ID: " << instance->getId() << '\n';
        std::cout << "Task ID: " << instance->getTask()->getId() << '\n';
        std::cout << "Ativada em: " << instance->getActivationTime() << '\n';
        std::cout << "Prazo absoluto: " << instance->getAbsoluteDeadline() << '\n';
        std::cout << "Tempo executada: " << instance->getExecutedTime() << '\n';
        std::cout << "Estado: " << getEnumValue(instance->getTaskState()) << '\n';
        std::cout << "Prazo perdido: " << instance->isDeadlineMissed() << '\n';

        std::cout << '\n';
        std::cout << "--------------------------" << '\n';
    }

    clearLastLine();

    std::cout << "=========================================================\n\n";
}

void Application::printCpus()
{
    std::cout << "==================== CPUS ====================" << '\n';

    for (CPU* cpu: simulation.getCpus())
    {
        std::cout << '\n';

        std::cout << "ID: " << cpu->getId() << '\n';
        std::cout << "Ativa: " << cpu->isActive() << '\n';
        std::cout << "Tempo ociosa: " << cpu->getIdleTicks() << '\n';
        std::cout << "ID da instância rodando: " << cpu->getTaskInstance()->getId() << '\n';

        std::cout << '\n';
        std::cout << "--------------------------" << '\n';
    }

    clearLastLine();

    std::cout << "===============================================\n\n";
}

void Application::printTasks()
{
    std::cout << "==================== TAREFAS ====================" << '\n';

    for (Task* task: simulation.getTasks())
    {
        std::cout << '\n';

        std::cout << "ID: " << task->getId() << '\n';
        std::cout << "Cor: " << task->getColor() << '\n';
        std::cout << "Chegada: " << task->getStart() << '\n';
        std::cout << "Duração: " << task->getDuration() << '\n';
        std::cout << "Período: " << task->getPeriod() << '\n';
        std::cout << "Prazo: " << task->getDeadline() << '\n';
        std::cout << "Vezes ativada: " << task->getActivationCount() << '\n';
        std::cout << "Finalizada: " << task->isFinished() << '\n';

        std::cout << '\n';
        std::cout << "--------------------------" << '\n';
    }

    clearLastLine();

    std::cout << "=================================================\n\n";
}
