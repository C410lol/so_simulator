#include "../include/ui/Application.h"

#include <iostream>
#include <limits>


Application::Application() = default;




void Application::start()
{
    //  Asks for the file path
    std::string answer;
    std::string filePath;
    printIntroduction(answer, filePath);

    simulation.initialize(filePath);

    std::string command;
    while (true)
    {
        clearScreen();
        printTitle();

        simulation.prerun();

        render();

        printCommands();
        std::cin >> command;
        if (command == "1")
            simulation.back();
        else if (command == "2")
            simulation.runAll();
        else if (command == "3")
            simulation.run();
        else
            break;
    }
}



